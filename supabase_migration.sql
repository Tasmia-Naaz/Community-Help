-- Community Help Connect feature migration for Supabase PostgreSQL.
-- Run after the existing users and resource_listings tables are present.

CREATE TABLE IF NOT EXISTS public.volunteer_verifications (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    volunteer_id integer NOT NULL UNIQUE REFERENCES public.users(id) ON DELETE CASCADE,
    id_document_type varchar(40),
    id_document_path varchar(500),
    id_document_name varchar(255),
    id_document_content_type varchar(100),
    id_document_size integer,
    certificate_path varchar(500),
    certificate_name varchar(255),
    certificate_content_type varchar(100),
    certificate_size integer,
    volunteering_experience text,
    verification_status varchar(20) NOT NULL DEFAULT 'pending'
        CHECK (verification_status IN ('pending', 'approved', 'rejected', 'resubmitted', 'suspended')),
    verification_submitted_at timestamptz NOT NULL DEFAULT now(),
    verification_reviewed_at timestamptz,
    verification_reviewed_by integer REFERENCES public.users(id) ON DELETE SET NULL,
    verification_notes text
);
CREATE INDEX IF NOT EXISTS ix_volunteer_verifications_status
    ON public.volunteer_verifications(verification_status);

CREATE TABLE IF NOT EXISTS public.volunteer_verification_history (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    verification_id integer NOT NULL REFERENCES public.volunteer_verifications(id) ON DELETE CASCADE,
    action varchar(40) NOT NULL,
    status varchar(20) NOT NULL
        CHECK (status IN ('pending', 'approved', 'rejected', 'resubmitted', 'suspended')),
    message text,
    actor_id integer REFERENCES public.users(id) ON DELETE SET NULL,
    created_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS ix_volunteer_verification_history_verification_id
    ON public.volunteer_verification_history(verification_id);
CREATE INDEX IF NOT EXISTS ix_volunteer_verification_history_created_at
    ON public.volunteer_verification_history(created_at);

-- Existing volunteers are not implicitly trusted by this migration.
INSERT INTO public.volunteer_verifications (volunteer_id, verification_status)
SELECT id, 'pending'
FROM public.users
WHERE role = 'volunteer'
ON CONFLICT (volunteer_id) DO NOTHING;

INSERT INTO public.volunteer_verification_history (
    verification_id, action, status, message, actor_id
)
SELECT v.id, 'legacy_application_imported', 'pending',
       'Existing volunteer requires administrator review after migration.', NULL
FROM public.volunteer_verifications AS v
WHERE NOT EXISTS (
    SELECT 1
    FROM public.volunteer_verification_history AS h
    WHERE h.verification_id = v.id
);

CREATE TABLE IF NOT EXISTS public.conversations (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    help_seeker_id integer NOT NULL REFERENCES public.users(id) ON DELETE CASCADE,
    donor_id integer NOT NULL REFERENCES public.users(id) ON DELETE CASCADE,
    resource_listing_id integer REFERENCES public.resource_listings(id) ON DELETE SET NULL,
    status varchar(20) NOT NULL DEFAULT 'open' CHECK (status IN ('open', 'closed')),
    created_at timestamptz NOT NULL DEFAULT now(),
    updated_at timestamptz NOT NULL DEFAULT now(),
    CHECK (help_seeker_id <> donor_id)
);
CREATE INDEX IF NOT EXISTS ix_conversations_help_seeker_id ON public.conversations(help_seeker_id);
CREATE INDEX IF NOT EXISTS ix_conversations_donor_id ON public.conversations(donor_id);
CREATE INDEX IF NOT EXISTS ix_conversations_resource_listing_id ON public.conversations(resource_listing_id);
CREATE INDEX IF NOT EXISTS ix_conversations_status ON public.conversations(status);
CREATE INDEX IF NOT EXISTS ix_conversations_updated_at ON public.conversations(updated_at);

CREATE TABLE IF NOT EXISTS public.messages (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    conversation_id integer NOT NULL REFERENCES public.conversations(id) ON DELETE CASCADE,
    sender_id integer NOT NULL REFERENCES public.users(id) ON DELETE CASCADE,
    message_text varchar(2000) NOT NULL CHECK (length(message_text) BETWEEN 1 AND 2000),
    is_read boolean NOT NULL DEFAULT false,
    created_at timestamptz NOT NULL DEFAULT now(),
    read_at timestamptz
);
CREATE INDEX IF NOT EXISTS ix_messages_conversation_id ON public.messages(conversation_id);
CREATE INDEX IF NOT EXISTS ix_messages_sender_id ON public.messages(sender_id);
CREATE INDEX IF NOT EXISTS ix_messages_is_read ON public.messages(is_read);
CREATE INDEX IF NOT EXISTS ix_messages_created_at ON public.messages(created_at);
CREATE INDEX IF NOT EXISTS ix_messages_conversation_id_id
    ON public.messages(conversation_id, id);
CREATE INDEX IF NOT EXISTS ix_messages_conversation_unread
    ON public.messages(conversation_id, is_read, sender_id);

CREATE TABLE IF NOT EXISTS public.conversation_reports (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    conversation_id integer NOT NULL REFERENCES public.conversations(id) ON DELETE CASCADE,
    reporter_id integer NOT NULL REFERENCES public.users(id) ON DELETE CASCADE,
    reason varchar(1000) NOT NULL,
    created_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS ix_conversation_reports_conversation_id
    ON public.conversation_reports(conversation_id);
CREATE INDEX IF NOT EXISTS ix_conversation_reports_reporter_id
    ON public.conversation_reports(reporter_id);

-- Private verification-document bucket. The Flask server uses the service-role
-- key only after authenticating the application user and checking their role.
INSERT INTO storage.buckets (id, name, public, file_size_limit, allowed_mime_types)
VALUES (
    'volunteer-verification-documents',
    'volunteer-verification-documents',
    false,
    5242880,
    ARRAY['application/pdf', 'image/jpeg', 'image/png']
