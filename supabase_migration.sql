-- For direct Supabase Auth access, issue trusted app_metadata claims:
--   community_user_id = the matching public.users.id
--   role = volunteer or admin
-- Never set authorization claims through user-editable user_metadata.
DROP POLICY IF EXISTS "Volunteer uploads own verification documents" ON storage.objects;
CREATE POLICY "Volunteer uploads own verification documents"
ON storage.objects FOR INSERT TO authenticated
WITH CHECK (
    bucket_id = 'volunteer-verification-documents'
    AND (storage.foldername(name))[1] = 'volunteer'
    AND (auth.jwt() -> 'app_metadata' ->> 'role') = 'volunteer'
    AND (storage.foldername(name))[2] = (auth.jwt() -> 'app_metadata' ->> 'community_user_id')
);

DROP POLICY IF EXISTS "Volunteer and admins read verification documents" ON storage.objects;
CREATE POLICY "Volunteer and admins read verification documents"
ON storage.objects FOR SELECT TO authenticated
USING (
    bucket_id = 'volunteer-verification-documents'
    AND (
        (auth.jwt() -> 'app_metadata' ->> 'role') = 'admin'
        OR (
            (auth.jwt() -> 'app_metadata' ->> 'role') = 'volunteer'
            AND (storage.foldername(name))[1] = 'volunteer'
            AND (storage.foldername(name))[2] = (auth.jwt() -> 'app_metadata' ->> 'community_user_id')
        )
    )
);

